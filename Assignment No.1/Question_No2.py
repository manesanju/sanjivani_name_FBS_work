##### Q.2 : Write a program to calculate area of rectangle based on length and breadth.

#Take input for length and breadth
length = float(input('Enter a length:'))
breadth = float(input('Enter a breadth:'))

#Perform Operation
area_of_rec = length * breadth

#Display result
print(f'Area of rectangle {length} & {breadth} is {area_of_rec}.')